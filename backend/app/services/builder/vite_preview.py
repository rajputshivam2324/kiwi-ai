"""Ensure generated Vite apps accept reverse-proxied preview hostnames.

The project's own ``vite.config.*`` is authored by an LLM, so its shape is not
predictable: it may use ``defineConfig({...})``, ``defineConfig((env) => ({...}))``,
a bare ``export default {...}``, and it may or may not already declare a
``server`` block. Text-patching that file is unreliable — in particular,
appending a second ``server`` key silently loses the allowlist because the last
key in a JS object literal wins.

Instead we leave the project config untouched and generate a small wrapper
config that imports it and force-overrides ``server.host`` /
``server.allowedHosts``. Vite is then launched with ``--config <wrapper>``.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)

# Same order Vite itself uses to resolve a config file, so the wrapper composes
# whichever file Vite would have loaded on its own.
_CONFIG_NAMES = (
    "vite.config.js",
    "vite.config.mjs",
    "vite.config.ts",
    "vite.config.cjs",
    "vite.config.mts",
    "vite.config.cts",
)

#: Generated wrapper. Deliberately NOT one of Vite's auto-discovered names.
WRAPPER_CONFIG_NAME = "vite.kiwi.config.mjs"

_DEFAULT_VITE_CONFIG = """import {{ defineConfig }} from "vite";
import react from "@vitejs/plugin-react";

export default defineConfig({{
  plugins: [react()],
  server: {{
    host: true,
    allowedHosts: {allowed},
  }},
}});
"""

# NOTE: `mergeConfig` from vite is intentionally not used. It concatenates when
# either side is an array, so `allowedHosts: true` merged over
# `allowedHosts: ["localhost"]` yields `["localhost", true]` instead of `true`.
# A shallow spread with an explicit `server` override is deterministic.
_WRAPPER_TEMPLATE = """// Generated by Kiwi AI — do not edit. Rewritten on every preview start.
// Wraps {user_config} and forces the host allowlist required by the
// reverse-proxied live preview. The project config is left untouched.
import {{ defineConfig }} from "vite";
import userConfigExport from "./{user_config}";

const allowedHosts = {allowed};

export default defineConfig(async (env) => {{
  const resolved =
    typeof userConfigExport === "function"
      ? await userConfigExport(env)
      : userConfigExport;
  const base = resolved ?? {{}};

  return {{
    ...base,
    server: {{
      ...(base.server ?? {{}}),
      host: true,
      allowedHosts,
    }},
    preview: {{
      ...(base.preview ?? {{}}),
      host: true,
      allowedHosts,
    }},
  }};
}});
"""


def _allowed_hosts_literal(allowed_hosts: list[str] | bool) -> str:
    """Render the allowlist as a JS literal (``true`` allows any Host header)."""
    if allowed_hosts is True:
        return "true"
    if not allowed_hosts:
        return "true"
    return json.dumps(list(allowed_hosts))


def _find_user_config(project_path: Path) -> str | None:
    for name in _CONFIG_NAMES:
        if (project_path / name).is_file():
            return name
    return None


def ensure_vite_allowed_hosts(
    project_path: Path,
    allowed_hosts: list[str] | bool,
) -> str:
    """Make the project's dev server accept the proxied preview hostname.

    Returns the config filename (relative to ``project_path``) that Vite should
    be started with. Callers must pass it via ``--config``.
    """
    allowed_literal = _allowed_hosts_literal(allowed_hosts)
    user_config = _find_user_config(project_path)

    if user_config is None:
        target = project_path / "vite.config.ts"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            _DEFAULT_VITE_CONFIG.format(allowed=allowed_literal), encoding="utf-8"
        )
        logger.info("No vite config found; wrote %s with allowedHosts", target.name)
        return "vite.config.ts"

    wrapper = project_path / WRAPPER_CONFIG_NAME
    wrapper.write_text(
        _WRAPPER_TEMPLATE.format(user_config=user_config, allowed=allowed_literal),
        encoding="utf-8",
    )
    logger.info(
        "Wrote %s wrapping %s (allowedHosts=%s)",
        WRAPPER_CONFIG_NAME,
        user_config,
        allowed_literal,
    )
    return WRAPPER_CONFIG_NAME
